"""
Generate doc/agentic/tools.md from the tool registry of a built kicad-cli (tools/list over
stdio, with a private configuration).  --check fails when the file is not current.

    tools/agentic/gen-tool-reference.py [--kicad-cli build/agentic/kicad/kicad-cli] [--check]
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.abspath( os.path.join( os.path.dirname( __file__ ), "..", ".." ) )
OUTPUT = os.path.join( ROOT, "doc", "agentic", "tools.md" )

# Sections by tool-name prefix, in the order of the programs; the rest is the server's own.
SECTIONS = [
    ( "sch", "Schematic" ), ( "sym", "Symbol editor" ), ( "sim", "Simulator" ), ( "pcb", "PCB" ),
    ( "fp", "Footprint editor" ), ( "view3d", "3D viewer" ), ( "gerber", "Gerber viewer" ),
    ( "ds", "Drawing sheet editor" ), ( "calc", "Calculator" ), ( "cvpcb", "Assign footprints (CvPcb)" ),
    ( "lib", "Libraries" ), ( "pcm", "Plugin and content manager" ), ( "docs", "Documentation" ),
]


def tools_list( kicad_cli ):
    with tempfile.TemporaryDirectory() as config:
        env = dict( os.environ, KICAD_CONFIG_HOME=config, XDG_CONFIG_HOME=config )
        env.pop( "AGENTIC_TEST_HOOKS", None )
        messages = [
            { "jsonrpc": "2.0", "id": 1, "method": "initialize",
              "params": { "protocolVersion": "2025-06-18", "capabilities": {},
                          "clientInfo": { "name": "gen-tool-reference", "version": "1" } } },
            { "jsonrpc": "2.0", "method": "notifications/initialized" },
            { "jsonrpc": "2.0", "id": 2, "method": "tools/list" },
        ]
        run = subprocess.run( [ kicad_cli, "mcp", "--stdio" ], input="\n".join( json.dumps( m ) for m in messages ) + "\n",
                              capture_output=True, text=True, env=env, timeout=300 )

    for line in run.stdout.splitlines():
        reply = json.loads( line )

        if reply.get( "id" ) == 2:
            return reply["result"]["tools"]

    sys.exit( "no tools/list answer from " + kicad_cli + ":\n" + run.stderr[-2000:] )


def section_of( name ):
    prefix = name.split( "_" )[0]

    for key, title in SECTIONS:
        if prefix == key:
            return title

    return "Projects, files, history and server"


def type_of( schema ):
    t = schema.get( "type", "" )

    if isinstance( t, list ):
        t = " or ".join( t )

    if "enum" in schema:
        t = " | ".join( str( v ) for v in schema["enum"] )

    return t or "any"


def cell( text ):
    return str( text ).replace( "|", "\\|" ).replace( "\n", " " )


def render( tools ):
    order = [ title for _, title in SECTIONS ] + [ "Projects, files, history and server" ]
    by_section = { title: [] for title in order }

    for tool in tools:
        by_section[section_of( tool["name"] )].append( tool )

        # Every argument schema must be an object: strict clients reject the tool otherwise.
        for name, prop in tool.get( "inputSchema", {} ).get( "properties", {} ).items():
            if not isinstance( prop, dict ):
                sys.exit( f"{tool['name']}: the schema of argument '{name}' is {json.dumps( prop )}, not an object" )

    lines = [ "# Agentic KiCad tool reference", "",
              "Generated by `tools/agentic/gen-tool-reference.py` from the tool registry; do not edit.",
              f"{len( tools )} tools. Every tool also takes `project` (a project folder; default: the current one).",
              "" ]

    for title in [ "Projects, files, history and server" ] + [ t for _, t in SECTIONS ]:
        section = sorted( by_section[title], key=lambda t: t["name"] )

        if not section:
            continue

        lines += [ f"## {title}", "" ]

        for tool in section:
            schema = tool.get( "inputSchema", {} )
            props = { k: v for k, v in schema.get( "properties", {} ).items() if k != "project" }
            required = set( schema.get( "required", [] ) )
            lines += [ f"### `{tool['name']}`", "", tool.get( "description", "" ).strip(), "" ]

            if props:
                lines += [ "| Argument | Type | Required | Description |", "|---|---|---|---|" ]

                for name in sorted( props, key=lambda n: ( n not in required, n ) ):
                    p = props[name]
                    lines.append( f"| `{name}` | {cell( type_of( p ) )} | {'yes' if name in required else ''} | "
                                  f"{cell( p.get( 'description', '' ) )} |" )

                lines.append( "" )

    return "\n".join( lines ).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser( description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter )
    parser.add_argument( "--kicad-cli", default=os.environ.get( "KICAD_CLI", os.path.join( ROOT, "build", "agentic", "kicad", "kicad-cli" ) ) )
    parser.add_argument( "--check", action="store_true", help="fail if doc/agentic/tools.md is not current" )
    args = parser.parse_args()

    text = render( tools_list( args.kicad_cli ) )

    if args.check:
        current = open( OUTPUT ).read() if os.path.exists( OUTPUT ) else ""

        if current != text:
            sys.exit( "doc/agentic/tools.md is stale: run tools/agentic/gen-tool-reference.py" )

        print( "doc/agentic/tools.md is current" )
        return

    with open( OUTPUT, "w" ) as f:
        f.write( text )

    print( f"wrote {OUTPUT}" )


if __name__ == "__main__":
    main()
